void ma35d1_tsi_init(void)
{
	uint32_t version_code;
	int ret;

	if (!(mmio_read_32(SYS_CHIPCFG) & 0x100)) {
		/*
		 * TSI enabled. Invoke TSI command and return here.
		 */

		/* enable WHC1 clock */
		mmio_write_32(CLK_SYSCLK1, (mmio_read_32(CLK_SYSCLK1) | 0x20));

		ret = TSI_Get_Version(&version_code);
		if (ret != ST_SUCCESS) {
			/* TSI is not ready. Init TSI. */
			while (1) {
				ret = TSI_Get_Version(&version_code);
				if (ret == ST_SUCCESS) {
					printf("TSI F/W version: %x\n", version_code);
					break;
				}
				if (ret == ST_WAIT_TSI_SYNC) {
					printf("Wait TSI_Sync.\n");
					TSI_Sync();
				}
			}
		}

		/* Load TSI patch image for OTP read/program */
		ret = TSI_Load_Image((uint32_t)(uintptr_t)tsi_patch_image, sizeof(tsi_patch_image));
		if (ret == 0) {
			printf("Load TSI image successful.\n");
		} else {
			printf("Load TSI image failed!! %d\n", ret);
		}
	}
}
